export function getPlacesForDay(day: number | 'full'): Place[] {
  if (day === 'full') {
    return PLACES;
  }
  return PLACES.filter((p) => p.day === day).sort((a, b) => a.order - b.order);
}

export function getPlaceById(id: string): Place | undefined {
  return PLACES.find((p) => p.id === id);
}
